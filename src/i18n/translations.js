export function normalizeLanguage(value) {
  return value === 'en' ? 'en' : DEFAULT_LANGUAGE;
}

export function translate(language, text, replacements = {}) {
  const source = String(text ?? '');
  const result = normalizeLanguage(language) === 'en' ? (english[source] || english[source.replace(/\s+/g, ' ').trim()] || source) : source;
  return result.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(replacements, key) ? String(replacements[key]) : match);
}

/** Translate transient UI notifications at the moment they are emitted. */
export function translateCurrent(text, replacements = {}) {
  const active = typeof document !== 'undefined' ? document.documentElement.lang : DEFAULT_LANGUAGE;
  return translate(active, text, replacements);
}
